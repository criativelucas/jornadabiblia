export function getMonths(days: string[], targetMonths?: number): string[][] {
  if (!days || days.length === 0) return [];
  const numMonths = targetMonths && targetMonths > 0 ? targetMonths : Math.ceil(days.length / 30);
  const perMonth = Math.floor(days.length / numMonths);
  const months: string[][] = [];
  for (let m = 0; m < numMonths; m++) {
    const start = m * perMonth;
    const end = m === numMonths - 1 ? days.length : (m + 1) * perMonth;
    months.push(days.slice(start, end));
  }
  return months;
}

