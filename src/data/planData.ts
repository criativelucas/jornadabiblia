export function generateCustomDays(config: CustomPlanConfig): string[] {
  let books: BookData[];
  if (config.scope === "at") {
    books = BIBLE_BOOKS_DATA.filter((b) => b.testament === "AT");
  } else if (config.scope === "nt") {
    books = BIBLE_BOOKS_DATA.filter((b) => b.testament === "NT");
  } else if (config.scope === "livros") {
    books = BIBLE_BOOKS_DATA.filter((b) => config.selectedBooks.includes(b.name));
  } else {
    books = BIBLE_BOOKS_DATA;
  }

  const allChapters: { book: string; ch: number }[] = [];
  for (const b of books) {
    for (let c = 1; c <= b.chapters; c++) {
      allChapters.push({ book: b.name, ch: c });
    }
  }

  const total = allChapters.length;
  const days: string[] = [];
  const chsPerDay = total / Math.max(config.durationDays, 1);

  for (let d = 0; d < config.durationDays; d++) {
    const start = Math.round(d * chsPerDay);
    const end = Math.min(Math.round((d + 1) * chsPerDay), total);
    if (start >= total) {
      days.push("Revisão geral");
      continue;
    }
    const slice = allChapters.slice(start, end);
    if (slice.length === 0) {
      days.push("Revisão geral");
      continue;
    }

    const groups: string[] = [];
    let i = 0;
    while (i < slice.length) {
      const book = slice[i].book;
      const startCh = slice[i].ch;
      let j = i + 1;
      while (j < slice.length && slice[j].book === book) j++;
      const endCh = slice[j - 1].ch;
      groups.push(startCh === endCh ? `${book} ${startCh}` : `${book} ${startCh}-${endCh}`);
      i = j;
    }
    days.push(groups.join("; "));
  }

  return days;
}

export function getTotalChaptersForConfig(config: CustomPlanConfig): number {
  if (config.scope === "at") return 929;
  if (config.scope === "nt") return 260;
  if (config.scope === "livros") {
    return BIBLE_BOOKS_DATA.filter((b) => config.selectedBooks.includes(b.name)).reduce((s, b) => s + b.chapters, 0);
  }
  return 1189;
}

